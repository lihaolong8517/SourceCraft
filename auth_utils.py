import os
import json
from datetime import datetime

import sys

# 使用绝对路径确保Cookies目录可以被找到，无论当前工作目录是什么
APP_DIR = os.path.dirname(os.path.abspath(__file__))

def get_writable_data_path():
    """获取可写的应用数据目录（解决安装到 Program Files 无法写入的问题）"""
    if getattr(sys, 'frozen', False):
        # 打包环境：使用 %APPDATA%/SourceCraft
        base_dir = os.path.join(os.environ.get('APPDATA', os.path.expanduser('~')), 'SourceCraft')
    else:
        # 开发环境：使用当前目录
        base_dir = APP_DIR
    
    os.makedirs(base_dir, exist_ok=True)
    return base_dir

WRITABLE_BASE = get_writable_data_path()
COOKIE_DIR = os.path.join(WRITABLE_BASE, "cookies")

def get_cookie_file(domain):
    """
    Get the path to the cookie file for a specific domain.
    Creates the cookie directory if it doesn't exist.
    """
    if not os.path.exists(COOKIE_DIR):
        os.makedirs(COOKIE_DIR)
    
    # Sanitize domain to be a valid filename
    safe_domain = "".join([c for c in domain if c.isalpha() or c.isdigit() or c in ('-', '_', '.')]).rstrip()
    return os.path.join(COOKIE_DIR, f"{safe_domain}_cookies.txt")

def save_cookies(cookies, domain):
    """
    Save cookies to a Netscape format file.
    
    Args:
        cookies: List of cookie dictionaries (from CEF).
        domain: The domain these cookies belong to.
    """
    cookie_file = get_cookie_file(domain)
    
    with open(cookie_file, 'w', encoding='utf-8') as f:
        f.write("# Netscape HTTP Cookie File\n")
        f.write("# This file is generated by the application. Do not edit.\n")
        f.write(f"# Source: internal_browser\n")
        f.write(f"# ExtractedAt: {datetime.utcnow().isoformat()}Z\n\n")
        
        for cookie in cookies:
            # Netscape format:
            # domain  flag  path  secure  expiration  name  value
            
            domain_val = cookie.get('domain', '')
            # Normalize domain: ensure it is a string
            if not isinstance(domain_val, str):
                domain_val = str(domain_val or '')
            # Netscape tailmatch flag
            flag = "TRUE" if domain_val.startswith('.') else "FALSE"
            path = cookie.get('path', '/')
            secure = "TRUE" if cookie.get('secure', False) else "FALSE"
            # HttpOnly prefix if available
            if cookie.get('httponly', False):
                domain_out = f"#HttpOnly_{domain_val}"
            else:
                domain_out = domain_val
            
            # Expiration
            expires = cookie.get('expires', 0)
            if expires is None:
                # Session cookie: use 0 to indicate non-persistent
                expires = 0
            else:
                # CEF might return datetime or timestamp? 
                # Assuming timestamp or converting if needed.
                # If it's a datetime object:
                if isinstance(expires, datetime):
                    expires = int(expires.timestamp())
                else:
                    expires = int(expires)
            
            # 【关键修复】Session cookie (expires <= 0) 需要设置一个较长的过期时间
            # 否则 yt-dlp 会将其视为已过期而忽略
            import time
            if expires <= 0:
                # 设置为1年后过期
                expires = int(time.time()) + 365 * 24 * 60 * 60

            name = cookie.get('name', '')
            value = cookie.get('value', '')
            
            f.write(f"{domain_out}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}\n")
            # Write a tailmatch variant to improve matching on subdomains
            # If domain does not start with '.', also write a '.domain' line with flag TRUE
            if domain_val and not domain_val.startswith('.'):
                dot_domain = '.' + domain_val
                domain_out2 = f"#HttpOnly_{dot_domain}" if cookie.get('httponly', False) else dot_domain
                f.write(f"{domain_out2}\tTRUE\t{path}\t{secure}\t{expires}\t{name}\t{value}\n")
            
    return cookie_file
